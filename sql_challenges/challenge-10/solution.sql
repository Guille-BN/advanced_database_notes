CREATE TABLE DEV.TEAMS 
(
    TEAM_ID NUMBER(*,0),
    TEAM_NAME VARCHAR2(60),
    PRIMARY KEY (TEAM_ID)
);

CREATE TABLE DEV.PROJECTS 
(
    PROJECT_ID NUMBER(*,0),
    TEAM_ID NUMBER(*,0),
    PROJECT_NAME VARCHAR2(100),
    DESCRIPTION VARCHAR2(255),
    START_DATE DATE,
    END_DATE DATE,
    PRIMARY KEY (PROJECT_ID),
    FOREIGN KEY (TEAM_ID)
        REFERENCES DEV.TEAMS(TEAM_ID)
);

CREATE TABLE DEV.USERS 
(
    USER_ID NUMBER(*,0),
    TEAM_ID NUMBER(*,0),
    PROJECT_ID NUMBER(*,0),
    USERNAME VARCHAR2(40),
    EMAIL VARCHAR2(40),
    PASSWORD_HASH VARCHAR2(255),
    USER_ROLE VARCHAR2(40),
    CREATED_AT TIMESTAMP (6),
    PRIMARY KEY (USER_ID),
    FOREIGN KEY (TEAM_ID)
        REFERENCES DEV.TEAMS(TEAM_ID),
    FOREIGN KEY (PROJECT_ID)
        REFERENCES DEV.PROJECTS(PROJECT_ID)
);

CREATE TABLE DEV.SPRINTS 
(
    SPRINT_ID NUMBER(*,0),
    PROJECT_ID NUMBER(*,0),
    SPRINT_NAME VARCHAR2(50),
    START_DATE DATE,
    END_DATE DATE,
    STATUS VARCHAR2(30),
    PRIMARY KEY (SPRINT_ID),
    FOREIGN KEY (PROJECT_ID)
        REFERENCES DEV.PROJECTS(PROJECT_ID)
);

CREATE TABLE DEV.TASKS 
(
    TASK_ID NUMBER(*,0),
    SPRINT_ID NUMBER(*,0),
    PROJECT_ID NUMBER(*,0),
    ASSIGNEE_USER_ID NUMBER(*,0),
    TASK_NAME VARCHAR2(150),
    DESCRIPTION VARCHAR2(255),
    STATUS VARCHAR2(30),
    PRIORITY VARCHAR2(20),
    CREATED_AT TIMESTAMP (6),
    PRIMARY KEY (TASK_ID),
    FOREIGN KEY (SPRINT_ID)
        REFERENCES DEV.SPRINTS(SPRINT_ID),
    FOREIGN KEY (PROJECT_ID)
        REFERENCES DEV.PROJECTS(PROJECT_ID),
    FOREIGN KEY (ASSIGNEE_USER_ID)
        REFERENCES DEV.USERS(USER_ID)
);

CREATE TABLE DEV.TASK_LOGS 
(
    LOG_ID NUMBER(*,0),
    TASK_ID NUMBER(*,0),
    LOG_TIMESTAMP TIMESTAMP (6),
    LOG_CONTENT VARCHAR2(250),
    PRIMARY KEY (LOG_ID),
    FOREIGN KEY (TASK_ID)
        REFERENCES DEV.TASKS(TASK_ID)
);

CREATE TABLE DEV.ANALYTICS 
(
    ANALYTIC_ID NUMBER(*,0),
    PROJECT_ID NUMBER(*,0),
    TASK_ID NUMBER(*,0),
    USER_ID NUMBER(*,0),
    PREVIOUS_STATUS VARCHAR2(30),
    NEW_STATUS VARCHAR2(30),
    CHANGE_TIMESTAMP TIMESTAMP (6),
    TASKS_COMPLETED NUMBER(*,0),
    COMMITS_COUNT NUMBER(*,0),
    PRIMARY KEY (ANALYTIC_ID),
    FOREIGN KEY (PROJECT_ID)
        REFERENCES DEV.PROJECTS(PROJECT_ID),
    FOREIGN KEY (TASK_ID)
        REFERENCES DEV.TASKS(TASK_ID),
    FOREIGN KEY (USER_ID)
        REFERENCES DEV.USERS(USER_ID)
);

CREATE TABLE DEV.DBTOOLS$EXECUTION_HISTORY 
(
    ID NUMBER NOT NULL ENABLE
);


